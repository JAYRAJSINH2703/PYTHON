#Here is some Rules of Variable

# 1. Variable name always start with a alphabet 
# 2. In a Variable name blank space not allowed 
# 3. In a Variable name special symbol not allowed like (),?,!,{} except _ (underscore)
# 4. In a Variable name Special Character not allowed like @, #, $, %, ^, &, *, +, =, /, \, |, ~, `, <, > except _ (underscore)


